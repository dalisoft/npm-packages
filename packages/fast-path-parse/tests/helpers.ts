import assert from 'node:assert/strict';
import { describe, it } from 'node:test';

interface ITestBase<
  TName = string,
  TInput = string,
  TInputArgs = string[],
  TValidate = string,
  TExcepted = string
> {
  name: TName;
  input: TInput;
  test_input: TValidate;
  excepted: TExcepted;
  input_args?: TInputArgs;
}
interface ITestVariants<
  TName = string,
  TInput = string,
  TInputArgs = string[],
  TValidate = string,
  TExcepted = string
> extends ITestBase<TName, TInput, TInputArgs, TValidate, TExcepted> {
  variants: string[][];
}
interface ITestChild<
  TName = string,
  TInput = string,
  TInputArgs = string[],
  TValidate = string,
  TExcepted = string
> extends ITestBase<TName, TInput, TInputArgs, TValidate, TExcepted> {
  children: Array<
    | ITestBase<TName, TInput, TInputArgs, TValidate, TExcepted>
    | ITestVariants<TName, TInput, TInputArgs, TValidate, TExcepted>
    | ITestChild<TName, TInput, TInputArgs, TValidate, TExcepted>
  >;
}
interface ITestReturn<
  TName = string,
  TInput = string,
  TInputArgs = string[],
  TValidate = string,
  TExcepted = string
> {
  name: TName;
  args: [TInput, TValidate];
  excepted: TExcepted;
  input_args: TInputArgs;
}
interface ITestSuite<
  TName = string,
  TInput = string,
  TInputArgs = string[],
  TValidate = string,
  TExcepted = string
> {
  suite: string;
  tests: ITestReturn<TName, TInput, TInputArgs, TValidate, TExcepted>[];
}
type TestKind<
  TName = string,
  TInput = string,
  TInputArgs = string[],
  TValidate = string,
  TExcepted = string
> =
  | ITestBase<TName, TInput, TInputArgs, TValidate, TExcepted>
  | ITestVariants<TName, TInput, TInputArgs, TValidate, TExcepted>
  | ITestChild<TName, TInput, TInputArgs, TValidate, TExcepted>;

export function generateTest<
  TName = string,
  TInput = string,
  TInputArgs = string[],
  TValidate = string,
  TExcepted = string
>(
  test: TestKind<TName, TInput, TInputArgs, TValidate, TExcepted>,
  is_parent: false
): ITestReturn<TName, TInput, TInputArgs, TValidate, TExcepted>;
export function generateTest<
  TName = string,
  TInput = string,
  TInputArgs = string[],
  TValidate = string,
  TExcepted = string
>(
  test: TestKind<TName, TInput, TInputArgs, TValidate, TExcepted>,
  is_parent = true
): ITestSuite<TName, TInput, TInputArgs, TValidate, TExcepted> {
  const {
    name,
    input,
    // eslint-disable-next-line @typescript-eslint/naming-convention
    test_input,
    excepted,
    variants,
    children,
    // eslint-disable-next-line @typescript-eslint/naming-convention
    input_args = []
  } = test;

  if (variants) {
    return {
      suite: name,
      tests: (variants as string[][]).map(
        ([inputTemplate, testInputTemplate]) => {
          const inputIt =
            typeof inputTemplate === 'string'
              ? inputTemplate.replace(/%s/g, input)
              : input;
          const testInputIt =
            typeof testInputTemplate === 'string'
              ? testInputTemplate.replace(/%s/g, test_input)
              : test_input;

          return {
            args: [inputIt, testInputIt],
            excepted,
            input_args,
            name: inputIt
          };
        }
      )
    };
  }
  if (children) {
    return {
      suite: name,
      tests: (
        children as ITestChild<
          TName,
          TInput,
          TInputArgs,
          TValidate,
          TExcepted
        >[]
      ).map((child) => generateTest(child, false))
    };
  }
  if (!is_parent) {
    return { args: [input, test_input], excepted, input_args, name };
  }

  return {
    suite: name,
    tests: [
      { args: [input, test_input], excepted, input_args, name: test_input }
    ]
  };
}

/**
 * Registers `node:test` suites and cases generated by {@link generateTest}.
 * Compatible with both `bun test` and `node --test`.
 * @param suite Suite generated by {@link generateTest}
 * @param callee Runs the tested function and returns its result
 * @param callee.prepare The path (or pattern) given to the tested function
 * @param callee.input The value validated by the prepared function
 * @param callee.inputArgs Extra arguments (like options) for the tested function
 */
export function runTest(
  // biome-ignore lint/suspicious/noExplicitAny: generated suites hold arbitrary fixtures
  { suite, tests }: { suite: string; tests: any[] },
  // biome-ignore lint/suspicious/noExplicitAny: tested functions return arbitrary values
  callee: (prepare: any, input: any, inputArgs: any[]) => unknown
): void {
  describe(suite, () => {
    for (const test of tests) {
      if (test.args) {
        const { name, args, input_args, excepted } = test;
        const [prepare, input] = args;

        it(name, () => {
          assert.deepEqual(callee(prepare, input, input_args), excepted);
        });
      } else {
        runTest(test, callee);
      }
    }
  });
}
